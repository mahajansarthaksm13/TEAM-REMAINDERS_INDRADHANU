"""D4 · Build database/supabase/seed.sql from the mock CSVs in data/.

    python database/scripts/build_seed.py            # writes database/supabase/seed.sql

Reads:  data/companies.csv, data/products.csv, data/bins.csv, data/targets.csv,
        data/bin_public_keys.csv  (public keys from simulator/keygen.py)
Writes: companies, products, bins (genesis chain heads), targets,
        test bins VB-PUN-0900/0901/0902, the demo company + demo bin,
        and 50 deterministic DEV-ONLY QR codes per approved product.

Never writes scans: scans only ever enter through ingest.
Run it again after any CSV or key change and commit the new seed.sql.
"""

from __future__ import annotations

import csv
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data"
OUT = ROOT / "database" / "supabase" / "seed.sql"
GENESIS = "0" * 64
TEST_BINS = {"VB-PUN-0900": "active", "VB-PUN-0901": "revoked", "VB-PUN-0902": "active"}
DEMO_COMPANY = "d0000000-0000-4000-8000-00000000de00"
DEMO_BIN = "VB-PUN-9999-DEMO"
QR_PER_PRODUCT = 50


def rows(name: str) -> list[dict]:
    with open(DATA / name, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def q(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def dev_serial(product_code: str, n: int) -> str:
    """Deterministic so tests and the simulator can know a valid QR serial.
    DEV ONLY: never seed these into prod."""
    return hashlib.sha256(f"veribin-dev:{product_code}:{n}".encode()).hexdigest()[:32]


def main() -> None:
    keys = {r["bin_id"]: r["public_key"].strip() for r in rows("bin_public_keys.csv")}
    companies, products = rows("companies.csv"), rows("products.csv")
    bins, targets = rows("bins.csv"), rows("targets.csv")
    first_product = next(p for p in products if p["approved"].lower() == "true" and p["barcode"])

    out = ["-- GENERATED by database/scripts/build_seed.py. Do not edit by hand.",
           "-- No scans here: scans only enter through ingest.", ""]

    for c in companies:
        out.append(f"insert into public.companies (id, name, is_demo) values "
                   f"({q(c['id'])}, {q(c['name'])}, {c['is_demo'].lower()});")
    out.append(f"insert into public.companies (id, name, is_demo) values "
               f"({q(DEMO_COMPANY)}, 'VeriBin Demo Co', true);")

    for p in products:
        barcode = q(p["barcode"]) if p["barcode"] else "null"
        out.append(
            "insert into public.products (company_id, product_code, name, barcode, category, "
            f"unit_weight_g, approved) values ({q(p['company_id'])}, {q(p['product_code'])}, "
            f"{q(p['name'])}, {barcode}, {q(p['category'])}, {int(p['unit_weight_g'])}, "
            f"{p['approved'].lower()});")
    out.append("insert into public.products (company_id, product_code, name, barcode, category, "
               f"unit_weight_g, approved) values ({q(DEMO_COMPANY)}, 'P9999', 'Demo bottle', "
               "'8900000099999', 'cat1_rigid', 24, true);")
    out.append("select setval('public.product_code_seq', "
               "(select max(substr(product_code, 2)::int) from public.products "
               "where product_code <> 'P9999'));")

    missing = []

    def bin_row(bin_id: str, company: str, city: str, key: str, status: str, demo: bool) -> str:
        return ("insert into public.bins (id, company_id, city, public_key, status, chain_head, "
                f"is_demo, allow_backfill) values ({q(bin_id)}, {q(company)}, {q(city)}, {q(key)}, "
                f"{q(status)}, {q(GENESIS)}, {str(demo).lower()}, true);")

    for b in bins:
        if b["id"] not in keys:
            missing.append(b["id"])
            continue
        out.append(bin_row(b["id"], b["company_id"], b["city"], keys[b["id"]], "active", False))

    # Test bins all share VB-PUN-0900's key, so ONE secret (TEST_BIN_PRIVATE_KEY)
    # can test the active, revoked and two-bins-at-once cases. They are marked
    # is_demo so CI traffic stays out of reports, public stats, offline alerts
    # and the company's bin list (the web app hides is_demo bins).
    if "VB-PUN-0900" in keys:
        for bin_id, status in TEST_BINS.items():
            out.append(bin_row(bin_id, first_product["company_id"], "PUN", keys["VB-PUN-0900"],
                               status, True))
    else:
        missing.append("VB-PUN-0900")

    if DEMO_BIN in keys:
        out.append(bin_row(DEMO_BIN, DEMO_COMPANY, "PUN", keys[DEMO_BIN], "active", True))
    else:
        missing.append(DEMO_BIN)

    for t in targets:
        out.append("insert into public.targets (company_id, financial_year, category, target_kg) "
                   f"values ({q(t['company_id'])}, {q(t['financial_year'])}, {q(t['category'])}, "
                   f"{t['target_kg']});")

    for p in products + [{"product_code": "P9999", "approved": "true"}]:
        if p["approved"].lower() != "true":
            continue
        code = p["product_code"]
        out.append(
            "with b as (insert into public.qr_batches (product_id, quantity) "
            f"select id, {QR_PER_PRODUCT} from public.products where product_code = {q(code)} "
            "returning id, product_id) insert into public.qr_codes (serial, batch_id, product_id) "
            f"select x.serial, b.id, b.product_id from b, (values "
            + ", ".join(f"({q(dev_serial(code, n))})" for n in range(1, QR_PER_PRODUCT + 1))
            + ") as x(serial);")

    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    print(f"TEST_BARCODE={first_product['barcode']}")
    print(f"TEST_QR_SERIAL={dev_serial(first_product['product_code'], 1)}"
          f"   (product {first_product['product_code']})")
    if missing:
        print("MISSING public keys (run simulator/keygen.py --bin-id <id>): " + ", ".join(missing),
              file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
